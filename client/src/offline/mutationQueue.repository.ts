/**
 * Phase 6 — Offline-First Operations
 * Mutation Queue Repository
 *
 * Provides durable persistence for offline operations.
 * Phase 7 consumes this queue to perform actual synchronization.
 */

import { db } from './db';
import type { PendingMutation, MutationOperationType, MutationStatus } from './types';

export const mutationQueueRepository = {
  // ============================================================
  // ENQUEUE
  // ============================================================

  /**
   * Add a new mutation to the persistent queue.
   * The idempotencyKey must be generated by the caller and NEVER regenerated on retry.
   */
  async enqueue(mutation: PendingMutation): Promise<void> {
    // Guard against duplicate idempotency keys
    const existing = await db.mutationQueue
      .where('id')
      .equals(mutation.id)
      .first();

    if (existing) {
      console.warn(`[MutationQueue] Duplicate mutation id: ${mutation.id} — skipping`);
      return;
    }

    await db.mutationQueue.add(mutation);
    console.log(`[MutationQueue] Enqueued ${mutation.operationType} id=${mutation.id}`);
  },

  // ============================================================
  // QUERY
  // ============================================================

  /** Get all pending mutations (ordered by creation time, oldest first) */
  async getPending(): Promise<PendingMutation[]> {
    const all = await db.mutationQueue
      .where('status')
      .equals('PENDING')
      .toArray();
    return all.sort((a, b) => a.createdAt.localeCompare(b.createdAt));
  },

  /** Get all mutations for a specific mission */
  async getPendingForMission(missionId: string): Promise<PendingMutation[]> {
    const all = await db.mutationQueue
      .where('missionId')
      .equals(missionId)
      .toArray();
    return all
      .filter((m) => m.status === 'PENDING')
      .sort((a, b) => a.createdAt.localeCompare(b.createdAt));
  },

  /** Count pending mutations for display */
  async countPending(): Promise<number> {
    return db.mutationQueue.where('status').equals('PENDING').count();
  },

  /** Count pending mutations for a specific mission */
  async countPendingForMission(missionId: string): Promise<number> {
    const all = await db.mutationQueue.where('missionId').equals(missionId).toArray();
    return all.filter((m) => m.status === 'PENDING').length;
  },

  /** Get a mutation by its id */
  async getById(mutationId: string): Promise<PendingMutation | undefined> {
    return db.mutationQueue.get(mutationId);
  },

  /** Get mutations by entity id (e.g. all mutations for a task) */
  async getByEntityId(entityId: string): Promise<PendingMutation[]> {
    return db.mutationQueue.where('entityId').equals(entityId).toArray();
  },

  // ============================================================
  // STATUS UPDATES (Phase 7 consumption interface)
  // ============================================================

  /** Mark mutation as ready for Phase 7 sync engine */
  async markReadyForSync(mutationId: string): Promise<void> {
    await db.mutationQueue.update(mutationId, {
      status: 'READY_FOR_SYNC' as MutationStatus,
    });
  },

  /** Mark mutation as failed after sync attempt */
  async markFailed(mutationId: string, errorMessage?: string): Promise<void> {
    const mutation = await db.mutationQueue.get(mutationId);
    if (!mutation) return;

    await db.mutationQueue.update(mutationId, {
      status: 'FAILED' as MutationStatus,
      retryCount: mutation.retryCount + 1,
      lastAttemptAt: new Date().toISOString(),
      errorMessage,
    });
  },

  /** Update serverId for an entity once synced */
  async updateServerId(mutationId: string, serverId: string): Promise<void> {
    await db.mutationQueue.update(mutationId, { serverId });
  },

  /** Remove a mutation after successful sync */
  async remove(mutationId: string): Promise<void> {
    await db.mutationQueue.delete(mutationId);
  },

  /** Remove all mutations for a mission (e.g. after full sync) */
  async removeForMission(missionId: string): Promise<void> {
    await db.mutationQueue.where('missionId').equals(missionId).delete();
  },

  // ============================================================
  // HELPERS
  // ============================================================

  /** Build a standard PendingMutation from parts */
  buildMutation(params: {
    missionId: string;
    operationType: MutationOperationType;
    entityType: PendingMutation['entityType'];
    entityId: string;
    payload: Record<string, unknown>;
    actorId: string;
    deviceId: string;
    baseUpdatedAt?: string;
  }): PendingMutation {
    const now = new Date().toISOString();
    return {
      id: crypto.randomUUID(),
      missionId: params.missionId,
      operationType: params.operationType,
      entityType: params.entityType,
      entityId: params.entityId,
      payload: params.payload,
      actorId: params.actorId,
      deviceId: params.deviceId,
      idempotencyKey: crypto.randomUUID(), // stable per mutation
      createdAt: now,
      clientCreatedAt: now,
      status: 'PENDING',
      retryCount: 0,
      baseUpdatedAt: params.baseUpdatedAt,
    };
  },
};
